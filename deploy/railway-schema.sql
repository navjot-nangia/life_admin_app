CREATE TABLE IF NOT EXISTS dismissals (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS dismissals_user ON dismissals (user);
CREATE TABLE IF NOT EXISTS documents (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, item TEXT DEFAULT '' NOT NULL, name TEXT NOT NULL, type TEXT NOT NULL, size INTEGER NOT NULL, created TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS documents_user ON documents (user);
CREATE TABLE IF NOT EXISTS history (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, item TEXT NOT NULL, cycle INTEGER NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS history_user ON history (user);
CREATE UNIQUE INDEX IF NOT EXISTS history_cycle ON history (item, cycle);
CREATE TABLE IF NOT EXISTS items (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, data TEXT NOT NULL, version INTEGER DEFAULT 0 NOT NULL);
CREATE INDEX IF NOT EXISTS items_user ON items (user);
CREATE TABLE IF NOT EXISTS notifications (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, item TEXT NOT NULL, data TEXT NOT NULL, read INTEGER DEFAULT 0 NOT NULL, pushed INTEGER DEFAULT 0 NOT NULL);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications (user);
CREATE TABLE IF NOT EXISTS profiles (user TEXT PRIMARY KEY NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS subscriptions (id TEXT PRIMARY KEY NOT NULL, user TEXT NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS subscriptions_user ON subscriptions (user);
CREATE TABLE IF NOT EXISTS system (id TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
